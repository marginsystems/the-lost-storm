import assert from 'node:assert/strict';
import { test } from 'node:test';
import { cast, offset, run, shapeArena } from '../../test/shape-support.ts';
import { must } from '../../test/support.ts';
import type { SkillDef } from '../content/types.ts';
import { timeScaleAt } from './areas.ts';
import type { AuraReading } from './aura.ts';
import { heroAuras } from './aura.ts';
import { refreshPlayer } from './character.ts';
import type { World } from './types.ts';

void test('Held Breath travels with the hero, refreshes before expiry and drops both effects when it ends', (): void => {
  const world: World = shapeArena([]);
  world.player.bar = [null, null, 'held_breath', null, null, 'dodge_roll'];
  refreshPlayer(world);
  const skill: SkillDef = must(world.player.skills[2], 'Held Breath');
  const baseSpeed: number = world.player.stats.moveSpeed;
  assert.deepEqual(heroAuras(world, world.player), []);
  cast(world, 2, offset(1, 0));
  run(world, skill.cooldown + 0.5);
  const before: AuraReading = must(heroAuras(world, world.player)[0], 'still active when ready');
  assert.ok(before.timeLeft > skill.windup);
  const speed: number = world.player.stats.moveSpeed;
  assert.ok(speed > baseSpeed);
  world.player.pos = offset(6, 0);
  run(world, 0.1);
  assert.equal(timeScaleAt(world, 'monster', offset(12, 0), 0), 0.7);
  assert.equal(timeScaleAt(world, 'monster', offset(-5, 0), 0), 1);
  assert.equal(timeScaleAt(world, 'player', world.player.pos, 0), 1);
  cast(world, 2, offset(7, 0));
  run(world, 0.6);
  const refreshed: readonly AuraReading[] = heroAuras(world, world.player);
  assert.equal(refreshed.length, 1);
  assert.ok(must(refreshed[0], 'refreshed').timeLeft > before.timeLeft);
  assert.equal(world.player.stats.moveSpeed, speed);
  run(world, before.duration);
  assert.deepEqual(heroAuras(world, world.player), []);
  assert.equal(timeScaleAt(world, 'monster', offset(12, 0), 0), 1);
  assert.equal(world.player.stats.moveSpeed, baseSpeed);
});
