export const DOME_FRAGMENT: string = [
  'uniform vec3 uTint;',
  'uniform float uStrength;',
  'uniform float uTime;',
  'uniform float uPress;',
  'uniform float uAngle;',
  'uniform float uPressGlow;',
  'uniform float uPressWidth;',
  'varying vec3 vNormalView;',
  'varying vec3 vViewDir;',
  'varying float vHeight;',
  'varying float vAround;',
  'void main() {',
  '  float facing = clamp(1.0 - abs(dot(normalize(vNormalView), normalize(vViewDir))), 0.0, 1.0);',
  '  float rim = pow(facing, 3.4);',
  '  float shimmer = 0.5 + 0.5 * sin(uTime * 2.1 + vAround * 5.0 + vHeight * 7.0);',
  '  float foot = smoothstep(0.0, 0.18, vHeight);',
  '  float gap = abs(mod(vAround - uAngle + 3.14159265, 6.2831853) - 3.14159265);',
  '  float side = exp(-(gap * gap) / max(uPressWidth, 0.001));',
  '  float low = 1.0 - smoothstep(0.0, 0.7, vHeight);',
  '  float push = uPress * side * low * (0.75 + 0.25 * sin(uTime * 9.0 - vHeight * 18.0)) * uPressGlow;',
  '  float alpha = max((rim * (0.75 + 0.25 * shimmer) + 0.02) * foot * uStrength + push * foot, 0.0);',
  '  gl_FragColor = vec4(uTint * alpha, alpha);',
  '}',
].join('\n');

export const FLOOR_VERTEX: string = ['varying vec2 vPlane;', 'void main() {', '  vPlane = position.xy;', '  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);', '}'].join('\n');

export const FLOOR_FRAGMENT: string = [
  'uniform vec3 uTint;',
  'uniform float uStrength;',
  'uniform float uTime;',
  'uniform float uMark;',
  'uniform float uPress;',
  'uniform float uAngle;',
  'uniform float uPressGlow;',
  'uniform float uPressWidth;',
  'varying vec2 vPlane;',
  'void main() {',
  '  float d = length(vPlane);',
  '  float edge = smoothstep(0.9, 0.975, d) * (1.0 - smoothstep(0.975, 1.0, d));',
  '  float ripple = 0.5 + 0.5 * sin(d * 18.0 - uTime * 2.6);',
  '  float rings = uMark * (1.0 - smoothstep(0.0, 0.08, abs(fract(d * 3.0 - uTime * 1.5) - 0.5))) * (1.0 - smoothstep(0.85, 1.0, d));',
  '  float gap = abs(mod(atan(-vPlane.y, vPlane.x) - uAngle + 3.14159265, 6.2831853) - 3.14159265);',
  '  float push = uPress * exp(-(gap * gap) / max(uPressWidth, 0.001)) * edge * uPressGlow;',
  '  float alpha = max(edge * (0.8 + 0.2 * ripple) * uStrength + rings + push, 0.0);',
  '  gl_FragColor = vec4(uTint * alpha, alpha);',
  '}',
].join('\n');
